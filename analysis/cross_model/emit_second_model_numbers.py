"""A80 macros.

Reads analysis/second_model_screen.json for the eligibility/imbalance/truncation
numbers -- nothing there is recomputed.

It ALSO computes the A80.13 zero-variance filter counts directly from the four
result files. Those need only the guarded correct-count per prompt, no
tokenizer, so they are cheap; they are not in second_model_screen.json because
that screen predates the filter being discovered.

  $HOME/miniconda3/envs/vllm/bin/python emit_second_model_numbers.py
"""
import collections
import json
import os

EXP = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(EXP, "analysis", "second_model_screen.json")
OUT = os.path.abspath(os.path.join(EXP, "..", "..", "TRANSFER_OUT",
                                   "second_model_screen_numbers.tex"))
D = json.load(open(SRC))
RES = os.path.abspath(os.path.join(EXP, "..", "..", "unlearnability-rlvr", "results"))
FILES = {
    "Qwen2.5-0.5B ckpt1 (reference)":
        "qwen_0.5b_run1_simplelr_qwen_level1to4_sub1k@train_0.7_32_1024_None_0_qwen.json",
    "Llama-3.2-3B (screen800)":
        "e4_gate_llama3b_e4_screen800@test_0.7_32_1024_None_0_qwen.json",
    "Llama-3.2-3B (screen800 v2)":
        "e4_gate_llama3b_v2_e4_screen800_v2@test_0.7_32_1024_None_0_e4v2.json",
}


def _guarded(v):
    return int(v.get("score", 0)) == 1 and v.get("extracted_answer") != "[invalid]"


def zero_variance_counts(fname):
    """A80.13. A prompt is usable only if it has k >= K AND at least one
    INCORRECT rollout: GRPO drops any group whose rewards have zero variance
    (checkpoint_gradient_analysis.py:get_group_rewards, std_reward == 0)."""
    per = collections.defaultdict(list)
    for r in json.load(open(os.path.join(RES, fname))):
        per[int(r["question_id"])].append(_guarded(r.get("verification", {}) or {}))
    Q = sorted(per)
    k = [sum(per[q]) for q in Q]
    n = [len(per[q]) for q in Q]
    p = [ki / ni for ki, ni in zip(k, n)]
    med = sorted(p)[len(p) // 2] if len(p) % 2 else (
        sorted(p)[len(p) // 2 - 1] + sorted(p)[len(p) // 2]) / 2
    out = {"n_prompts": len(Q), "all_correct": sum(1 for ki, ni in zip(k, n) if ki == ni)}
    for K in (4, 6, 8, 11):
        rows = {"hard_before": 0, "hard_after": 0, "easy_before": 0, "easy_after": 0}
        for ki, ni, pi in zip(k, n, p):
            if ki < K:
                continue
            side = "hard" if pi <= med else "easy"
            rows[side + "_before"] += 1
            if ki < ni:
                rows[side + "_after"] += 1
        out[K] = rows
    return out


ZV = {m: zero_variance_counts(f) for m, f in FILES.items()}

REF = "Qwen2.5-0.5B ckpt1 (reference)"
LL = "Llama-3.2-3B (screen800)"
LV = "Llama-3.2-3B (screen800 v2)"
QS = "Qwen2.5-1.5B base (E5 gate)"
