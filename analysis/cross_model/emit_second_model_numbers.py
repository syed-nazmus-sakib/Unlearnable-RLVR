A("% cap-1024 passes for the SAMPLE-SIZE CONFOUND arm. No training run, no")
A("% Chen labels. Generated by EXPERIMENTS/E1_rescue/emit_second_model_numbers.py")
A("% from analysis/second_model_screen.json. Nothing is recomputed here.")
A("%")
A("% THE CLAIM BOUNDARY TRAVELS WITH EVERY NUMBER IN THIS FILE. Groups are")
A("% defined by INITIAL-POLICY PASS RATE, which is NOT Chen's definition. Any")
A("% result from this arm replicates the ESTIMATOR CONFOUND on a second model")
A("% and architecture. It says nothing about the unlearnable set, nothing about")
A("% whether the phenomenon reproduces, and nothing about training -- there is")
A("% no training run in it. Whenever the paper writes \"second model\", it must")
A("% say in the SAME SENTENCE what it is a second model OF.")
A("%")
A("% THE SELECTION ASYMMETRY TRAVELS WITH THE REASSURANCE, in one sentence:")
A("% contamination among the rollouts actually used is \\smTruncCorrectLlama")
A("% percent, BUT the hard pool loses \\smTruncPoolHardLlama percent of its")
A("% rollouts to the cap against the easy pool's \\smTruncPoolEasyLlama percent,")
A("% so truncation filters the two groups unequally and the resulting bias has")
A("% UNKNOWN SIGN in the group the test is about.")
A("%")
A("% tau = 0.1 CANNOT DEFINE THE GROUPS. On every model the tau-defined hard")
A("% group has ZERO members eligible at K=4. The median split is forced, not")
A("% chosen; the quartile split returns zero eligible hard prompts everywhere.")
A("%")
A("% ==================================================================")
A("% THE ZERO-VARIANCE FILTER (A80.13), a THIRD eligibility constraint.")
A("%")
A("% (a) IT IS GRPO'S OWN RULE, NOT A SCRIPT ARTEFACT. A group whose rollouts")
A("%     all carry the same reward has zero advantage and contributes no")
A("%     gradient; checkpoint_gradient_analysis.py:get_group_rewards drops the")
A("%     prompt on std_reward == 0. A prompt is usable only if it has k >= K")
A("%     AND at least one INCORRECT rollout.")
A("%")
A("% (b) IT CAN ONLY EVER TOUCH THE EASY GROUP, so it shrinks the two arms")
A("%     ASYMMETRICALLY. A below-median prompt cannot have a full sweep of")
A("%     correct rollouts, so the hard count is identical before and after on")
A("%     every model at every K. The easy group is the only one that loses")
A("%     anything, and how much it loses depends entirely on how many prompts")
A("%     the model solves on all \\smBudget rollouts: \\smAllCorrectRef of")
A("%     \\smNRef for the 0.5B against \\smAllCorrectLlama of \\smNLlama for")
A("%     Llama. The reference arm loses a third of its easy group; Llama loses")
A("%     one prompt.")
A("%")
A("% (c) IT WAS FOUND BY RUNNING THE CODE, NOT BY READING IT. A80.3 counted")
A("%     k >= K alone and was wrong to. The filter surfaced only when a probe")
A("%     invocation returned \"Retained 0 prompts with positive rollouts\" on a")
A("%     prompt with four correct rollouts and no incorrect ones.")
A("% ==================================================================")
A("")
A("\\newcommand{\\smBudget}{32}")
A("\\newcommand{\\smCap}{1024}")
A("")

for m, t in TAG.items():
    a = D[m]
    A(f"% ---- {m} ----")
    A(f"\\newcommand{{\\smN{t}}}{{{a['n_prompts']}}}")
    A(f"\\newcommand{{\\smMeanP{t}}}{{{a['mean_p']:.4f}}}")
    A(f"\\newcommand{{\\smTruncAll{t}}}{{{a['trunc_overall']*100:.2f}}}")
    A(f"\\newcommand{{\\smTruncCorrect{t}}}{{{a['trunc_among_correct']*100:.2f}}}")
    A(f"\\newcommand{{\\smTauHard{t}}}{{{a['tau_hard_prompts']}}}")
    A(f"\\newcommand{{\\smTauHardEligible{t}}}{{{a['tau_hard_eligible_at_four']}}}")
    for K, w in W.items():
        r = a["splits"]["median"][K]
        A(f"\\newcommand{{\\smHard{w}{t}}}{{{r['hard']}}}")
        A(f"\\newcommand{{\\smEasy{w}{t}}}{{{r['easy']}}}")
        A(f"\\newcommand{{\\smElig{w}{t}}}{{{r['eligible_total']}}}")
        im = r["imbalance"]
        A(f"\\newcommand{{\\smImbal{w}{t}}}"
          f"{{{'--' if im != im else format(im, '.2f')}}}")
        q = a["splits"]["quartile"][K]
        A(f"\\newcommand{{\\smQuartHard{w}{t}}}{{{q['hard']}}}")
    A("")

# ---- A80.13: the zero-variance filter, before -> after, per model and K ----
A("% ---- zero-variance filter: eligible BEFORE -> AFTER, and the loss ----")
for m, t in [(REF, "Ref"), (LL, "Llama"), (LV, "LlamaV")]:
    z = ZV[m]
    A(f"\\newcommand{{\\smAllCorrect{t}}}{{{z['all_correct']}}}")
    for K, w in W.items():
        r = z[int(K)]
        for side in ("hard", "easy"):
            sw = side.capitalize()
            A(f"\\newcommand{{\\smZv{sw}Before{w}{t}}}{{{r[side + '_before']}}}")
            A(f"\\newcommand{{\\smZv{sw}After{w}{t}}}{{{r[side + '_after']}}}")
            A(f"\\newcommand{{\\smZv{sw}Lost{w}{t}}}"
              f"{{{r[side + '_before'] - r[side + '_after']}}}")
