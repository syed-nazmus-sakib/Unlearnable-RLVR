# the N/K ceiling, and the pool asymmetry that must travel with any result
A("% ---- the N/K cap: a property of matched-K designs, not of our estimator ----")
for K, w in W.items():
    A(f"\\newcommand{{\\smCeil{w}}}{{{32 / int(K):.1f}}}")
    A(f"\\newcommand{{\\smMinRate{w}}}{{{int(K) / 32:.3f}}}")
