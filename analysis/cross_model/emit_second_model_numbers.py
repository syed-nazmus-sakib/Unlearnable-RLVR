A("% ---- the selection asymmetry, Llama screen800 at K=4 ----")
r = D[LL]["splits"]["median"]["4"]
A(f"\\newcommand{{\\smTruncPoolHardLlama}}{{{r['trunc_hard']*100:.2f}}}")
A(f"\\newcommand{{\\smTruncPoolEasyLlama}}{{{r['trunc_easy']*100:.2f}}}")
A(f"\\newcommand{{\\smTruncCorrHardLlama}}{{{r['trunc_correct_hard']*100:.2f}}}")
A(f"\\newcommand{{\\smTruncCorrEasyLlama}}{{{r['trunc_correct_easy']*100:.2f}}}")
A(f"\\newcommand{{\\smPoolRatioLlama}}"
  f"{{{r['trunc_hard'] / r['trunc_easy']:.1f}}}")

open(OUT, "w").write("\n".join(L) + "\n")
n = sum(1 for x in L if x.startswith("\\newcommand"))
