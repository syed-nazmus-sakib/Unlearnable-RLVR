a(f"\\newcommand{{\\senNeededGpuHours}}{{{extra * CELL_H:.0f}}}")
a("")
a("% ---- variance decomposition: the floor no subsample count removes ----")
a(f"\\newcommand{{\\senSePrompt}}{{{se['Prompt']:.4f}}}")
a(f"\\newcommand{{\\senSeSub}}{{{se['Sub']:.4f}}}")
a(f"\\newcommand{{\\senSeJoint}}{{{se['Joint']:.4f}}}")
a(f"\\newcommand{{\\senMdePrompt}}{{{np.exp(Z80*se['Prompt']):.4f}}}")
a(f"\\newcommand{{\\senMdeSub}}{{{np.exp(Z80*se['Sub']):.4f}}}")
a(f"\\newcommand{{\\senMdeJoint}}{{{np.exp(Z80*se['Joint']):.4f}}}")
a("")
a("% ---- populations: common support, and the eligibility asymmetry (A61.5) ----")
a(f"\\newcommand{{\\senCommonDu}}{{{d['common_support']['du71']}}}")
a(f"\\newcommand{{\\senCommonLearn}}{{{d['common_support']['learnable']}}}")
a(f"\\newcommand{{\\senCommonEasy}}{{{d['common_support']['easy']}}}")
for g, mac, tot in (("du71", "Du", 28), ("learnable", "Learn", 28), ("easy", "Easy", 40)):
    n = len(d["eligibility_swap"][g]["only_1024"])
    a(f"\\newcommand{{\\senSwap{mac}}}{{{n}}}")
    a(f"\\newcommand{{\\senSwap{mac}Tot}}{{{tot}}}")
    a(f"\\newcommand{{\\senSwap{mac}Pct}}{{{100*n/tot:.0f}}}")

txt = "\n".join(L) + "\n"
out = os.path.join(AN, "sensitivity_numbers.tex")
