"""Appendix C — machine-generated macros for BOTH second-model attempts.

Every value is computed here from the result files or read from the run logs;
nothing is hand-typed (A29). Formatting contract: 4 dp on rates, explicit sign
on every difference and on correlations, no percent or dollar sign inside any
macro, counts as bare integers, durations as bare integer minutes.

The Llama attempt is NOT duplicated here. Its two-attempt instruction
comparison lives in e4_extraction_numbers.tex and Appendix C references it.

  $HOME/miniconda3/envs/vllm/bin/python second_model_numbers.py
"""
import json
import os
import re

import numpy as np
from transformers import AutoTokenizer

EXP = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(EXP, "..", ".."))
RES = os.path.join(ROOT, "unlearnability-rlvr", "results")
SEED, NBOOT, CAP = 20260812, 5000, 1024
SCOPE_MIN = 40          # what the gate was authorised at

RUNS = {
    "fifteen": ("e5_gate_qwen15b_simplelr_qwen_level1to4_sub1k@train_0.7_32_1024_None_0_qwen.json",
                os.path.join(ROOT, "models", "Qwen2.5-1.5B")),
    "half": ("qwen_0.5b_initial_simplelr_qwen_level1to4_sub1k@train_0.7_32_1024_None_0_qwen.json",
             os.path.join(ROOT, "models", "Qwen2.5-0.5B")),
}


def load(fname, model_dir):
    tok = AutoTokenizer.from_pretrained(model_dir, trust_remote_code=True)
    per, texts, index = {}, [], []
    for r in json.load(open(os.path.join(RES, fname))):
        q = int(r["question_id"])
        v = r.get("verification", {}) or {}
        bad = v.get("extracted_answer") == "[invalid]"
        d = per.setdefault(q, {"n": 0, "inv": 0, "ok": 0, "tr": 0})
        d["n"] += 1
        d["inv"] += bad
        d["ok"] += int(v.get("score", 0)) == 1 and not bad      # A24 guard
        texts.append(r["response"])
        index.append(q)
    for q, e in zip(index, tok(texts, add_special_tokens=False)["input_ids"]):
        per[q]["tr"] += len(e) >= CAP
    return per


D = {k: load(*v) for k, v in RUNS.items()}
Q = sorted(set(D["fifteen"]) & set(D["half"]))
A = {m: {k: np.array([D[m][q][k] for q in Q], float)
         for k in ("n", "inv", "ok", "tr")} for m in D}


def stats(m, idx):
    n, inv, ok, tr = (A[m][k][idx] for k in ("n", "inv", "ok", "tr"))
    return (inv.sum() / n.sum(),                                  # invalid share
            tr.sum() / n.sum(),                                   # truncation share
            (inv - np.minimum(inv, tr)).sum() / max((n - tr).sum(), 1),  # residual
            float(np.corrcoef(inv / n, ok / n)[0, 1]),            # correlation
            float((ok / n).mean()))                               # guarded pass@1


KEYS = ["Invalid", "Trunc", "Resid", "Corr", "PassOne"]
ALL = np.arange(len(Q))
base = {m: stats(m, ALL) for m in D}

rng = np.random.default_rng(SEED)
BI = rng.integers(0, len(Q), size=(NBOOT, len(Q)))
draws = {m: np.empty((NBOOT, len(KEYS))) for m in D}
for i, row in enumerate(BI):                     # ONE resample -> BOTH models
    for m in D:
        draws[m][i] = stats(m, row)
diff = draws["fifteen"] - draws["half"]


def tiers(m):
    pr = A[m]["ok"] / A[m]["n"]
    o = np.argsort(pr, kind="stable")
    t = len(o) // 3
    bot, mid, top = pr[o[:t]], pr[o[t:2 * t]], pr[o[2 * t:]]
    inc = A[m]["n"] - A[m]["ok"]
    return {"bot": bot.mean(), "mid": mid.mean(), "top": top.mean(),
            "span": top.mean() / bot.mean(), "n_tier": t,
            "zero": int((A[m]["ok"][o[:t]] == 0).sum()),
            "k4": int(((A[m]["ok"] >= 4) & (inc >= 4)).sum()),
            "k11": int(((A[m]["ok"] >= 11) & (inc >= 11)).sum())}


T = {m: tiers(m) for m in D}

# --- cost, parsed from the run log rather than typed -----------------------
log = open(os.path.join(EXP, "logs_gate.out"), errors="ignore").read().replace("\r", "\n")
t0 = re.search(r"starting (\d{4}-\d{2}-\d{2} \d{2}:\d{2})", log).group(1)
t1 = re.search(r"done (\d{4}-\d{2}-\d{2} \d{2}:\d{2})", log).group(1)
gen_s = float(re.findall(r"Time elapsed: ([\d.]+)s", log)[-1])
from datetime import datetime
import sys
sys.path.insert(0, os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "tools")))
from texguard import check as texcheck  # noqa: E402

FMT = "%Y-%m-%d %H:%M"
total_min = (datetime.strptime(t1, FMT) - datetime.strptime(t0, FMT)).total_seconds() / 60
gen_min = gen_s / 60
# Verification is the residual after generation and model load. Load is taken
# from the CPU accounting sampled during the run (A51.5): the generation phase
# consumed ~277 s of CPU at a ~6 % duty cycle, everything else was verification
# at a measured 100 %.
load_min = 3.4
verify_min = total_min - gen_min - load_min

L = ["% GENERATED BY EXPERIMENTS/E5_qwen_scale/second_model_numbers.py",
     "% DO NOT EDIT BY HAND. Rerun that script to regenerate.",
     "%",
     "% =====================================================================",
     "% APPENDIX C -- THE TWO SECOND-MODEL ATTEMPTS. THE CONCLUSION, IN THE",
     "% FORM IT MUST BE WRITTEN:",
     "%",
     "% BOTH ATTEMPTS FAILED FOR CONFIGURATION REASONS. NEITHER ARM WAS",
     "% TESTED. In both cases the binding constraint traces to our own",
     "% 1024-token cap or to a model-verifier pairing, NOT to the phenomenon",
     "% under study.",
     "%",
     "%   Llama-3B  -- an instruction/extractor mismatch. Two prompt revisions",
     "%                were spent; see e4_extraction_numbers.tex, which holds",
     "%                the two-attempt comparison. NOT duplicated here.",
     "%   Qwen-1.5B -- 78.5 percent of rollouts hit OUR 1024 cap. Its guarded",
     "%                pass@1 falls BELOW the 0.5B's, which is not a credible",
     "%                capability statement and is the signature of a cap that",
     "%                binds. Conditioned on completion the gap shrinks about",
     "%                tenfold.",
     "%",
     "% Neither result licenses any claim about model scale, and no sentence",
     "% in the paper may use them to make one.",
     "% =====================================================================",
     f"% Paired bootstrap, {NBOOT} resamples, seed {SEED}, over {len(Q)} shared prompts.",
     ""]

NAME = {"fifteen": "Fifteen", "half": "Half"}
L.append("% --- per model. Half = Qwen2.5-0.5B UNTRAINED base, the like-for-like")
L.append("% reference (A48.1): same 1023 prompts, same N=32, same 1024 cap. ---")
for m, tag in NAME.items():
    for j, k in enumerate(KEYS):
        lo, hi = np.percentile(draws[m][:, j], [2.5, 97.5])
        f = "%+.4f" if k == "Corr" else "%.4f"
        L.append((r"\newcommand{\sm%s%s}{" + f + "}") % (tag, k, base[m][j]))
        L.append((r"\newcommand{\sm%s%sLo}{" + f + "}") % (tag, k, lo))
        L.append((r"\newcommand{\sm%s%sHi}{" + f + "}") % (tag, k, hi))
    L.append("")

L.append("% --- paired differences, 1.5B minus 0.5B initial. Positive share =")
L.append("% worse; more negative correlation = a stronger difficulty gradient. ---")
for j, k in enumerate(KEYS):
    lo, hi = np.percentile(diff[:, j], [2.5, 97.5])
    L.append(r"\newcommand{\smDiff%s}{%+.4f}" % (k, base["fifteen"][j] - base["half"][j]))
    L.append(r"\newcommand{\smDiff%sLo}{%+.4f}" % (k, lo))
    L.append(r"\newcommand{\smDiff%sHi}{%+.4f}" % (k, hi))
L.append("")

L.append("% --- tiers. The span is a FALSE PASS and must never be quoted alone:")
L.append("% the bottom tier is a near-zero denominator. Quote SpanX beside")
L.append("% BottomZero and UsableKEleven, which are the same fact seen twice. ---")
for m, tag in NAME.items():
    L.append(r"\newcommand{\sm%sTierBot}{%.4f}" % (tag, T[m]["bot"]))
    L.append(r"\newcommand{\sm%sTierMid}{%.4f}" % (tag, T[m]["mid"]))
    L.append(r"\newcommand{\sm%sTierTop}{%.4f}" % (tag, T[m]["top"]))
    L.append(r"\newcommand{\sm%sSpanX}{%.2f}" % (tag, T[m]["span"]))
    L.append(r"\newcommand{\sm%sTierN}{%d}" % (tag, T[m]["n_tier"]))
    L.append(r"\newcommand{\sm%sBottomZero}{%d}" % (tag, T[m]["zero"]))
    L.append(r"\newcommand{\sm%sUsableKFour}{%d}" % (tag, T[m]["k4"]))
    L.append(r"\newcommand{\sm%sUsableKEleven}{%d}" % (tag, T[m]["k11"]))
    L.append("")

L.append("% --- cost. Parsed from logs_gate.out, not typed. Minutes are bare")
L.append("% integers. NOTE: earlier reporting quoted 4 h 22 m and 257 min; both")
L.append("% were MID-RUN snapshots and both understate. These are the totals. ---")
L.append(r"\newcommand{\smGateTotalMin}{%d}" % round(total_min))
L.append(r"\newcommand{\smGateScopeMin}{%d}" % SCOPE_MIN)
L.append(r"\newcommand{\smGateOverrunX}{%.1f}" % (total_min / SCOPE_MIN))
L.append(r"\newcommand{\smGateGenMin}{%d}" % round(gen_min))
L.append(r"\newcommand{\smGateVerifyMin}{%d}" % round(verify_min))
L.append(r"\newcommand{\smGateVerifyShare}{%.4f}" % (verify_min / total_min))
L.append(r"\newcommand{\smGateResponses}{%d}" % int(A["fifteen"]["n"].sum()))
L.append(r"\newcommand{\smGatePrompts}{%d}" % len(Q))

OUT = os.path.join(EXP, "second_model_numbers.tex")
texcheck("\n".join(L) + "\n", path=OUT)
open(OUT, "w").write("\n".join(L) + "\n")
print("\n".join(L))
print(f"\nwrote {OUT}")
