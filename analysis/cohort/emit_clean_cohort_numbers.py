"""Emit analysis/clean_cohort_numbers.tex — A70.4/A70.5, Section 6's two
published numbers alongside their clean-cohort values, with intervals.

Reads analysis/a70_clean_cohort.json. Nothing is transcribed.

  $HOME/miniconda3/envs/vllm/bin/python emit_clean_cohort_numbers.py
"""
import json
import os
import sys

EXP = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(EXP, "..", "tools")))
from texguard import check as texcheck  # noqa: E402

AN = os.path.join(EXP, "analysis")
d = json.load(open(os.path.join(AN, "a70_clean_cohort.json")))
P, C, D = d["published"], d["clean"], d["paired_delta"]
GRP = {"du71": "Du", "learnable": "Learnable", "easy": "Easy"}
POP = {"natural": "Natural", "cohortB": "CohortB", "k11own": "KElevenOwn"}
LADDER = ["NatFull", "NatFullClean", "NatPub", "NatClean",
          "MatOwn", "MatOwnClean", "MatPub", "MatClean"]

L = []
a = L.append
a("% clean_cohort_numbers.tex -- A70.4/A70.5. Generated by")
a("% EXPERIMENTS/E1_rescue/emit_clean_cohort_numbers.py from")
a("% analysis/a70_clean_cohort.json. Do not hand-edit.")
a("%")
a("% TWO VALUES, NEITHER A CORRECTION OF THE OTHER.")
a("%   \\cleanPubMatched is faithful to the definition under audit: `unlearnable'")
a("%     is Chen's label and it is defined on trained runs, so the published")
a("%     number is the right number for the claim it audits.")
a("%   \\cleanMatched is the value on the prompts whose INITIAL-policy behaviour")
a("%     matches their label -- the policy the gradients are actually measured")
a("%     on. Report both. Do not present either as superseding the other.")
a("%")
a("% ORDER OF DISCOVERY, STATED HONESTLY. We found this mismatch AFTER seeing")
a("% the results, so dropping the \\cleanMmCohortBDuBad prompts is post-hoc and")
a("% must be labelled post-hoc. What makes it defensible is that the criterion")
a("% is principled and pre-specifiable -- a label defined on TRAINED runs tested")
a("% against gradients measured on the INITIAL policy, with the threshold tau =")
a("% \\cleanTau already fixed by the paper -- and that it is not fitted to any")
a("% outcome: the rule is stated without reference to a cosine, a ratio or a")
a("% direction of movement. Both halves go in the paper. The rule is principled;")
a("% the discovery was late.")
a("%")
a("% THE SHARE INTERVAL IS THE REAL NEWS, AND IT IS NOT GOOD FOR EITHER VALUE.")
a("% The published \\cleanPubShare\\,\\% was printed WITHOUT an interval. Computed")
a("% here it is [\\cleanPubShareLo, \\cleanPubShareHi], and the clean value")
a("% \\cleanShare\\,\\% carries [\\cleanShareLo, \\cleanShareHi]. BOTH intervals")
a("% contain 50. The sentence `just under half' -- and equally `more than half'")
a("% and `about half' -- is not supported by either cohort. What the data")
a("% supports is that matching removes a substantial but imprecisely estimated")
a("% share of the log gap. Print the interval or print no share at all.")
a("%")
a("% THE PAIRED DIFFERENCE, on shared bootstrap draws, is the honest summary of")
a("% how much the mismatch moves things: the matched ratio by")
a("% \\cleanDeltaMatched\\ [\\cleanDeltaMatchedLo, \\cleanDeltaMatchedHi], which")
a("% STRADDLES ZERO, and the share by \\cleanDeltaShare\\ points")
a("% [\\cleanDeltaShareLo, \\cleanDeltaShareHi], which does not. The movement in")
a("% the ratio is not resolved at this n; do not call it established.")
a("%")
a("% BOOTSTRAP. Seed \\cleanSeed, \\cleanBootReps replicates, percentile 2.5/97.5")
a("% -- the same family as the published intervals (guard_attrition.py for the")
a("% natural term, decompose_move.py:boot_ratio for the matched one). ONE")
a("% deliberate difference: within a replicate the easy prompt draw is shared")
a("% between the natural and matched easy means, and likewise for D_u, because")
a("% the share is a function of both terms and drawing them separately would")
a("% give an interval on a quantity nobody computes. The published cohort is")
a("% recomputed under this same procedure and reproduces the published CIs")
a("% ([\\cleanPubNatLo, \\cleanPubNatHi] against the printed [2.09, 2.59];")
a("% [\\cleanPubMatchedLo, \\cleanPubMatchedHi] against [1.26, 1.88]), so the")
a("% procedure is not doing the work.")
a("%")
a("% EVERYTHING IS ON COHORT B (\\cleanPubNEasy easy / \\cleanPubNDu D_u), per")
a("% A28.1. See \\cleanConvNote below: A70's first pass did not, and that is")
a("% where its `convention' remark came from.")
a("")
a(f"\\newcommand{{\\cleanTau}}{{{d['tau']:.1f}}}")
a(f"\\newcommand{{\\cleanSeed}}{{{d['seed']}}}")
a(f"\\newcommand{{\\cleanBootReps}}{{{d['nboot']:,}}}".replace(",", "{,}"))
a("")
a("% ---- the published cohort B, recomputed here under the shared-draw bootstrap ----")
a(f"\\newcommand{{\\cleanPubNEasy}}{{{P['n_easy']}}}")
a(f"\\newcommand{{\\cleanPubNDu}}{{{P['n_du']}}}")
a(f"\\newcommand{{\\cleanPubNat}}{{{P['nat']:.4f}}}")
a(f"\\newcommand{{\\cleanPubNatLo}}{{{P['ci']['nat'][0]:.4f}}}")
a(f"\\newcommand{{\\cleanPubNatHi}}{{{P['ci']['nat'][1]:.4f}}}")
a(f"\\newcommand{{\\cleanPubMatched}}{{{P['matched']:.4f}}}")
a(f"\\newcommand{{\\cleanPubMatchedLo}}{{{P['ci']['matched'][0]:.4f}}}")
a(f"\\newcommand{{\\cleanPubMatchedHi}}{{{P['ci']['matched'][1]:.4f}}}")
a(f"\\newcommand{{\\cleanPubShare}}{{{100*P['share']:.1f}}}")
a(f"\\newcommand{{\\cleanPubShareLo}}{{{100*P['ci']['share'][0]:.1f}}}")
a(f"\\newcommand{{\\cleanPubShareHi}}{{{100*P['ci']['share'][1]:.1f}}}")
a("")
a("% ---- the clean cohort: both sides restricted to label-consistent prompts ----")
a(f"\\newcommand{{\\cleanNEasy}}{{{C['n_easy']}}}")
a(f"\\newcommand{{\\cleanNDu}}{{{C['n_du']}}}")
a(f"\\newcommand{{\\cleanNat}}{{{C['nat']:.4f}}}")
a(f"\\newcommand{{\\cleanNatLo}}{{{C['ci']['nat'][0]:.4f}}}")
a(f"\\newcommand{{\\cleanNatHi}}{{{C['ci']['nat'][1]:.4f}}}")
a(f"\\newcommand{{\\cleanMatched}}{{{C['matched']:.4f}}}")
a(f"\\newcommand{{\\cleanMatchedLo}}{{{C['ci']['matched'][0]:.4f}}}")
a(f"\\newcommand{{\\cleanMatchedHi}}{{{C['ci']['matched'][1]:.4f}}}")
a(f"\\newcommand{{\\cleanShare}}{{{100*C['share']:.1f}}}")
a(f"\\newcommand{{\\cleanShareLo}}{{{100*C['ci']['share'][0]:.1f}}}")
a(f"\\newcommand{{\\cleanShareHi}}{{{100*C['ci']['share'][1]:.1f}}}")
a("")
a("% ---- paired difference, clean minus published, on the SAME draws ----")
a(f"\\newcommand{{\\cleanDeltaMatched}}{{{D['matched'][0]:+.4f}}}")
a(f"\\newcommand{{\\cleanDeltaMatchedLo}}{{{D['matched'][1]:+.4f}}}")
a(f"\\newcommand{{\\cleanDeltaMatchedHi}}{{{D['matched'][2]:+.4f}}}")
a(f"\\newcommand{{\\cleanDeltaShare}}{{{100*D['share'][0]:+.2f}}}")
a(f"\\newcommand{{\\cleanDeltaShareLo}}{{{100*D['share'][1]:+.2f}}}")
a(f"\\newcommand{{\\cleanDeltaShareHi}}{{{100*D['share'][2]:+.2f}}}")
a("")
a("% ---- mismatch shares, ALL THREE GROUPS AND ALL THREE POPULATIONS ----")
a("% Direction is group-specific and the paper must say so: du71 and learnable")
a("% are labelled on TRAINED runs, so a mismatch is an initial rate ABOVE tau;")
a("% easy is labelled on the INITIAL policy, so its mismatch is a rate AT OR")
a("% BELOW tau -- and there is no timing gap for it to open. That is why the")
a("% contamination is one-sided: the numerator group is clean at")
a("% \\cleanMmCohortBEasyPct\\,\\% and the denominator is")
a("% \\cleanMmNaturalDuPct\\,\\% naturally, \\cleanMmCohortBDuPct\\,\\% under")
a("% matching. `learnable' shares the problem for the same reason as D_u.")
for pop, pm in POP.items():
    for g, gm in GRP.items():
        e = d["mismatch"][pop][g]
        a(f"\\newcommand{{\\cleanMm{pm}{gm}N}}{{{e['n']}}}")
        a(f"\\newcommand{{\\cleanMm{pm}{gm}Bad}}{{{e['bad']}}}")
        a(f"\\newcommand{{\\cleanMm{pm}{gm}Pct}}{{{e['pct']:.1f}}}")
a(f"\\newcommand{{\\cleanMmDuMaxRate}}"
  f"{{{max(d['mismatch_rates_du_natural']):.4f}}}")
a(f"\\newcommand{{\\cleanMmDuMinRate}}"
  f"{{{min(d['mismatch_rates_du_natural']):.4f}}}")
a("")
a("% ---- A70.5: what the 1.5350/1.539 difference ACTUALLY was ----")
a("% A70 called it an averaging convention. IT WAS NOT. The two conventions --")
a("% averaging per prompt across subsamples before the ratio, or taking each")
a("% subsample's group mean first -- are algebraically identical on a fixed")
a("% cohort, and are verified identical here (\\cleanConvPubCellFirst against")
a("% \\cleanConvPubPromptFirst). The whole difference is COHORT: A70 used the")
a("% K=11-own eligible easy set (\\cleanConvKownNEasy prompts) instead of cohort")
a("% B (\\cleanPubNEasy), i.e. it silently restored the two easy prompts cohort B")
a("% drops for guard attrition, \\cleanConvDropped. That is precisely the cohort")
a("% mixing A28.1 forbids, in the entry that was auditing a cohort problem.")
a("% Recorded so nobody reads the two levels as a discrepancy -- and so the")
a("% wrong explanation does not outlive the right one.")
a(f"\\newcommand{{\\cleanConvPubCellFirst}}"
  f"{{{d['convention']['published_cohortB_cellfirst']:.4f}}}")
a(f"\\newcommand{{\\cleanConvPubPromptFirst}}"
  f"{{{d['convention']['published_cohortB_promptfirst']:.4f}}}")
a(f"\\newcommand{{\\cleanConvKown}}{{{d['convention']['k11own_cellfirst']:.4f}}}")
a(f"\\newcommand{{\\cleanConvKownNEasy}}"
  f"{{{d['convention']['k11own_n']['easy']}}}")
a(f"\\newcommand{{\\cleanConvDropped}}"
  f"{{{', '.join(d['convention']['easy_only_in_k11own'])}}}")
a(f"\\newcommand{{\\cleanConvDiff}}"
  f"{{{abs(d['convention']['published_cohortB_cellfirst'] - d['convention']['k11own_cellfirst']):.4f}}}")
a(f"\\newcommand{{\\cleanConvCleanKown}}{{{d['convention']['clean_k11own']:.4f}}}")
a("\\newcommand{\\cleanConvNote}{cohort, not convention}")
a("")
a("% ---- the reconciliation ladder: every level A70 printed, reproduced ----")
a("% A70's clean levels cleaned the D_u SIDE ONLY. The primary clean numbers")
a("% above clean BOTH sides. No step in this ladder is unexplained.")
for key, (name, ne, nd, v) in zip(LADDER, d["ladder"]):
    a(f"% {name}, {ne} easy / {nd} D_u")
    a(f"\\newcommand{{\\cleanLad{key}}}{{{v:.4f}}}")
    a(f"\\newcommand{{\\cleanLad{key}NEasy}}{{{ne}}}")
    a(f"\\newcommand{{\\cleanLad{key}NDu}}{{{nd}}}")

txt = "\n".join(L) + "\n"
out = os.path.join(AN, "clean_cohort_numbers.tex")
nm = texcheck(txt, path=out)
open(out, "w").write(txt)
print(txt)
print(f"wrote {out}  ({nm} macros, texguard clean)")
