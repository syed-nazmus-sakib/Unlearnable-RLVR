"""Emit analysis/instability_numbers.tex — A69, what set instability does to a
reported number. Reads the two result JSONs; nothing is transcribed.

  $HOME/miniconda3/envs/vllm/bin/python emit_instability_numbers.py
"""
import json
import os
import sys

EXP = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(EXP, "..", "tools")))
from texguard import check as texcheck  # noqa: E402

AN = os.path.join(EXP, "analysis")
V2 = json.load(open(os.path.join(AN, "a69_du_anchored.json")))       # primary
V1 = json.load(open(os.path.join(AN, "a69_set_instability.json")))   # label-faithful
CI_LO, CI_HI = 2.09, 2.59          # published sampling CI on the natural ratio
CI_W = CI_HI - CI_LO
MATERIAL = 0.25
WORD = {"8": "Eight", "16": "Sixteen", "32": "ThirtyTwo",
        "128": "OneTwentyEight", "200": "TwoHundred"}

L = []
a = L.append
a("% instability_numbers.tex -- A69: what set instability does to a reported")
a("% number. Generated by EXPERIMENTS/E1_rescue/emit_instability_numbers.py.")
a("%")
a("% ONLY THE WIDTHS ARE THE RESULT. THE LEVELS ARE NOT.")
a("% Re-drawing the threshold test does not reproduce the published label, so")
a("% the level of the ratio under this procedure is NOT comparable to 2.6657:")
a("%   - re-drawing the WHOLE test puts `learnable` prompts into the denominator")
a("%     (they are initially flagged BY DEFINITION), pulling the level to 2.03;")
a("%   - anchoring on D_u instead retains only prompts that still flag, i.e. the")
a("%     lowest-pass-rate and most attenuated ones, pushing it to 2.81.")
a("% Both anchorings are wrong as levels and agree as widths. Quote widths.")
a("%")
a("% EVERYTHING HERE IS CONDITIONAL ON THE A65 BINOMIAL MODEL. The sets are")
a("% generated by that model, so the consequence is conditional on it. The model")
a("% is prospectively validated (A66.3, branch A, 2 of 2) but under-predicts")
a("% agreement by about 0.03, so it slightly OVERSTATES instability.")
a("%")
a("% TWO BIAS DIRECTIONS, AND WE DO NOT ASSUME THEY CANCEL. The model's 0.03")
a("% under-prediction inflates these widths. The restriction to the")
a("% \\insCoverage prompts with stored gradients deflates them, because that")
a("% cohort was selected for extreme pass rates and so sits further from tau")
a("% than a random prompt and flickers less. They run opposite ways; no")
a("% cancellation is claimed and neither is corrected for.")
a("%")
a("% MATERIALITY was fixed before computing: a width of \\insMaterial or more,")
a("% which is half the width of the sampling CI this paper already prints on the")
a("% same ratio, [\\insPubCiLo, \\insPubCiHi], width \\insPubCiWidth. Below half,")
a("% set choice is second-order against an interval we already report; at or")
a("% above it, set choice contributes an error of the same order as one we do")
a("% report -- and unlike that one, nobody reports it.")
a("%")
a("% N=32 IS UNRESOLVED. The two variants straddle the threshold there")
a("% (\\insWidthThirtyTwo anchored against \\insWidthAltThirtyTwo label-faithful).")
a("% It is reported as unresolved and must not be called either way.")
a("")
a(f"\\newcommand{{\\insMaterial}}{{{MATERIAL:.2f}}}")
a(f"\\newcommand{{\\insPubCiLo}}{{{CI_LO:.2f}}}")
a(f"\\newcommand{{\\insPubCiHi}}{{{CI_HI:.2f}}}")
a(f"\\newcommand{{\\insPubCiWidth}}{{{CI_W:.2f}}}")
a(f"\\newcommand{{\\insCoverage}}{{130}}")
a(f"\\newcommand{{\\insCoverageTotal}}{{1023}}")
a(f"\\newcommand{{\\insCoveragePct}}{{{100*130/1023:.1f}}}")
a(f"\\newcommand{{\\insModelBias}}{{0.03}}")
a("")
a("% ---- primary: D_u-anchored, the question 'which prompts landed in the set' ----")
for n, w in WORD.items():
    d = V2[n]
    half = (d["hi"] - d["lo"]) / 2
    a(f"% N={n}: width {d['width']:.4f} = {100*d['width']/CI_W:.0f}% of the published CI width")
    a(f"\\newcommand{{\\insMedian{w}}}{{{d['median']:.4f}}}")
    a(f"\\newcommand{{\\insLo{w}}}{{{d['lo']:.4f}}}")
    a(f"\\newcommand{{\\insHi{w}}}{{{d['hi']:.4f}}}")
    a(f"\\newcommand{{\\insWidth{w}}}{{{d['width']:.4f}}}")
    a(f"\\newcommand{{\\insHalfWidth{w}}}{{{half:.2f}}}")
    a(f"\\newcommand{{\\insWidthVsCi{w}}}{{{100*d['width']/CI_W:.0f}}}")
    a(f"\\newcommand{{\\insMaterialQ{w}}}"
      f"{{{'material' if d['width'] >= MATERIAL else 'not material'}}}")
    a(f"\\newcommand{{\\insDuKept{w}}}{{{d['du_kept']:.1f}}}")
    a("")
a("% ---- secondary: label-faithful variant, for the N=32 straddle ----")
for n, w in WORD.items():
    a(f"\\newcommand{{\\insWidthAlt{w}}}{{{V1[n]['width']:.4f}}}")
a("")
a("% ---- the sentence the paper may make ----")
a(f"\\newcommand{{\\insErrEight}}{{{(V2['8']['hi']-V2['8']['lo'])/2:.2f}}}")
a(f"\\newcommand{{\\insErrSixteen}}{{{(V2['16']['hi']-V2['16']['lo'])/2:.2f}}}")
a(f"\\newcommand{{\\insRobustFrom}}{{128}}")

out = os.path.join(AN, "instability_numbers.tex")
nm = texcheck(L, path=out)
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(x for x in L if not x.startswith("%")))
print(f"\nwrote {out}  ({nm} macros, texguard clean)")
