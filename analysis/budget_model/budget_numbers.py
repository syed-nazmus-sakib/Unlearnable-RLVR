"""A49 macros. Reads analysis/budget_jaccard.json; nothing hand-typed (A29).
Contract: 4 dp unsigned on Jaccards and rates, explicit sign on differences,
no percent or dollar sign inside a macro, counts as bare integers."""
import json, os
EXP = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(EXP, "analysis", "budget_jaccard.json")))
T = ["% GENERATED BY EXPERIMENTS/E1_rescue/budget_numbers.py -- DO NOT EDIT BY HAND.",
     "%",
     "% =====================================================================",
     "% WHAT THIS MEASURES, AND THE SENTENCE MUST NOT DRIFT FROM IT (A49.5):",
     "% it tests whether OUR central object is stable to the EVALUATION",
     "% budget. It does NOT reproduce Chen's configuration, because our",
     "% training ALSO ran at 1024 and their policy was trained to use 5120.",
     "% Any description omitting the second clause is wrong.",
     "%",
     "% The comparator is MEASURED, not assumed: budJFloor is the Jaccard",
     "% between two independent 1024 passes of the SAME checkpoint (A36).",
     "% =====================================================================",
     r"\newcommand{\budN}{%d}" % d["n_prompts"],
     r"\newcommand{\budTau}{%.1f}" % d["tau"],
     r"\newcommand{\budJ}{%.4f}" % d["jaccard"],
     r"\newcommand{\budJLo}{%.4f}" % d["lo"],
     r"\newcommand{\budJHi}{%.4f}" % d["hi"],
     r"\newcommand{\budJFloor}{%.4f}" % d["floor"],
     r"\newcommand{\budJFloorLo}{%.4f}" % d["floor_lo"],
     r"\newcommand{\budJFloorHi}{%.4f}" % d["floor_hi"],
     r"\newcommand{\budFlagTenTwentyFour}{%d}" % d["flag_1024"],
     r"\newcommand{\budFlagFiftyOneTwenty}{%d}" % d["flag_5120"],
     r"\newcommand{\budStayed}{%d}" % d["stayed"],
     r"\newcommand{\budExited}{%d}" % d["exited"],
     r"\newcommand{\budEntered}{%d}" % d["entered"],
     "",
     "% Pass rate barely moves; truncation and extraction failure both fall 3x.",
     r"\newcommand{\budPassTenTwentyFour}{%.4f}" % d["pass_1024"],
     r"\newcommand{\budPassFiftyOneTwenty}{%.4f}" % d["pass_5120"],
     r"\newcommand{\budPassDiff}{%+.4f}" % (d["pass_5120"] - d["pass_1024"]),
     r"\newcommand{\budTruncTenTwentyFour}{%.4f}" % d["trunc_1024"],
     r"\newcommand{\budTruncFiftyOneTwenty}{%.4f}" % d["trunc_5120"],
     r"\newcommand{\budInvalidTenTwentyFour}{%.4f}" % d["inv_1024"],
     r"\newcommand{\budInvalidFiftyOneTwenty}{%.4f}" % d["inv_5120"],
     ]
OUT = os.path.join(EXP, "analysis", "budget_numbers.tex")
open(OUT, "w").write("\n".join(T) + "\n")
print("\n".join(T)); print("\nwrote", OUT)
