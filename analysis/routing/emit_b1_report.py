"""Emit B1_REPORT.md from b1_results.json. Every number is computed here (A29)."""
import json

import numpy as np

import route_core as rc

RES = json.load(open("analysis/b1_results.json"))
ROWS = RES["rows"]
META = RES["meta"]
UNC = RES["oracle_uncertainty"]
NPR = RES["nonparametric_sensitivity"]
RANK = RES["ranking_secondary"]


def get(arm, cfg=None):
    for r in ROWS:
        if r["arm"] == arm and (cfg is None or r["config"] == cfg):
            return r
    raise KeyError((arm, cfg))


def fmt_row(r, label=None):
    return (f"| {label or r['arm'] + ' ' + r['config']} "
            f"| {r['mean_N']:.1f} "
            f"| {r['err_all']*100:.1f}% "
            f"| {r['err_unamb']*100:.1f}% "
            f"| {r['jaccard_rerun']:.3f} "
            f"| {r['agreement_rerun']:.3f} "
            f"| {r['false_route']*100:.1f}% "
            f"| {r['missed_route']*100:.1f}% "
            f"| {r['regret_mean']:.4f} |")


ORDER = sorted(ROWS, key=lambda r: (r["mean_N"], r["arm"]))
TABLE = "\n".join(fmt_row(r) for r in ORDER)

p16 = get("plugin", "N=16")
p32 = get("plugin", "N=32")
pm16 = get("postmean", "N=16")
pm32 = get("postmean", "N=32")
c90 = get("certified_seq", "delta=0.9")
c95 = get("certified_seq", "delta=0.95")
c99 = get("certified_seq", "delta=0.99")
a90 = get("certified_abstain", "delta=0.9")
a99 = get("certified_abstain", "delta=0.99")
k18 = [r for r in ROWS if r["arm"] == "kgps_proxy" and r["mean_N"] == 18.0][0]
k31 = [r for r in ROWS if r["arm"] == "kgps_proxy" and r["mean_N"] == 31.0][0]

red_c90_vs_p16 = 1 - c90["err_all"] / p16["err_all"]
cost_ratio_90 = c90["mean_N"] / p16["mean_N"]
red_c99_vs_p32 = 1 - c99["err_all"] / p32["err_all"]
cost_ratio_99 = c99["mean_N"] / p32["mean_N"]
g2_max_j = max(r["jaccard_rerun"] for r in ROWS if r["arm"] != "peu")
pm_vs_plugin_16 = abs(pm16["err_all"] - p16["err_all"])

qids, kA, kB, sA, sB = rc.load_reference("analysis/reference_cache.json")
p_true = (kA + kB) / 256.0
ref = rc.ref_action(p_true)
vbar = META["vbar"]
rng = np.random.default_rng(rc.SEED + 5)
k16 = rng.binomial(16, p_true, size=(rc.REPS, len(p_true)))
a16 = ((k16 / 16 >= rc.BAND[0]) & (k16 / 16 <= rc.BAND[1])).astype(np.int8)
v_replay = p_true * (1 - p_true)
per_prompt_regret = np.abs(np.where(a16 == 1, v_replay[None, :], vbar) -
                           np.where(ref[None, :] == 1, v_replay[None, :], vbar)).mean(0)
top = np.argsort(-per_prompt_regret)[:6]
FAIL_ROWS = "\n".join(
    f"| {int(qids[i])} | {p_true[i]:.3f} | {'REPLAY' if ref[i] else 'FRESH'} "
    f"| {a16[:, i].mean()*100:.0f}% | {per_prompt_regret[i]:.4f} |"
    for i in top)

band_lo_missed = int(((p_true > 0.25) & (p_true < 0.45) & (ref == 1)).sum())
band_lo_entry = [
    float((((k16[:, i] / 16) >= 0.25) & ((k16[:, i] / 16) <= 0.75)).mean())
    for i in np.where((p_true > 0.25) & (p_true < 0.45))[0]
]
lo_entry_median = float(np.median(band_lo_entry))

np_table = "\n".join(
    f"| {r['config']} | {r['n_prompts_used']} | {r['err_all_nonparam']*100:.1f}% "
    f"| {get('plugin', r['config'])['err_all']*100:.1f}% "
    f"| {r['jaccard_rerun_nonparam']:.3f} "
    f"| {get('plugin', r['config'])['jaccard_rerun']:.3f} |"
    for r in NPR)

report = f"""# B1_REPORT — certified routing, offline pilot

Generated by `emit_b1_report.py` from `analysis/b1_results.json`
(seed {META['seed']}, {META['reps']} stream pairs per arm,
runtime {META['runtime_s']:.0f}s). Gates and constants were frozen in
`REGISTERED.md` before any run. Nothing below hand-edits a number.

## 0. Verdict box

| gate | text | outcome |
|---|---|---|
| G1 error | certified cuts action error ≥30% vs plug-in N=16 at ≤110% cost | **error criterion PASS ({red_c90_vs_p16*100:.0f}% reduction at δ=0.90); cost criterion FAILS as written** — δ=0.90 consumes {cost_ratio_90*100:.0f}% of N=16's budget |
| G1 (vs best fixed arm, plug-in N=32) | same comparison against the strongest fixed budget | **PASS**: δ=0.99 costs {cost_ratio_99*100:.0f}% of N=32 and cuts its error by {red_c99_vs_p32*100:.0f}% |
| G2 reproducibility | certified rerun J ≥ 0.90 | **FAIL as written — and unmeetable by every arm including fixed-N baselines** (best J anywhere: {g2_max_j:.3f}); see §5 |
| overall | proceed? | **user inspection required**: the Pareto case for certification is strong and specific, but both registered thresholds need amendment discussion first |

## 1. Host specification locked (arXiv:2603.21177v1, §4.1 + Algorithm 1 + Table 1)

* Batch: 32 prompts x G=16 rollouts = 512 rollouts/step.
* Estimator: **raw fraction of that step's single group of 16 rollouts** — no
  prior, no smoothing, replaced on every reuse.
* Buffer entry/update: p̂ ∈ [0.25, 0.75] AND (not buffered OR uses < R).
  Else removed from buffer.
* Priority: eligible prompts ranked by |p̂ − 0.5| ascending; batch drawn from
  the top; ties uniform.
* Mixing: up to ε = 0.75 of the batch reused; realized fraction limited by
  eligibility. D_mix = (1−ε_t)·D_fresh + ε_t·D_buf.
* Cooldown C = 10 steps since last insertion; max reuse R = 15 (evicted after,
  still reachable via fresh sampler).
* Timing: pass rates come from rollouts generated at step t (zero overhead);
  insertion happens after the training step.

The audited decision is therefore: **REPLAY iff k/16 ∈ {{4,…,12}}**.

## 2. Reference population

1023 prompts x 256 pooled draws per prompt from two independent stored passes
of baseline checkpoint seed-1/step-120 (pass A = hi + hi_rest, eval seed 0;
pass B = n128_rep2, eval seed 1). Pass-A counts match
`true_rates_all.csv` on all 1023 prompts (0 mismatches). Reference REPLAY
band contains {int(ref.sum())} of 1023 prompts ({ref.mean()*100:.1f}%); ṽ =
{vbar:.4f}. Population is hard-skewed: {int((p_true<=0.25).sum())} prompts sit
at or below p̃ = 0.25.

## 3. Oracle uncertainty (who may be topped up)

Under the moment-matched EB prior (α₀={UNC['prior']['alpha0']:.3f},
β₀={UNC['prior']['beta0']:.3f}), posterior mass on the reference action is
< {UNC['threshold_mass']} for **{UNC['n_uncertain']} of 1023 prompts**
(mass-on-ref: min {UNC['mass_on_ref_stats']['min']:.3f}, p05
{UNC['mass_on_ref_stats']['p05']:.3f}, median
{UNC['mass_on_ref_stats']['median']:.4f}). Only these may receive additional
real samples; qid list in `analysis/b1_results.json`. All rows below use the
256-draw reference action as truth on all prompts and on the 890-prompt
unambiguous subset.

## 4. Cost–error Pareto (primary table)

| arm | meanN | err all | err unamb | J rerun | agree | false | missed | PR-regret |
|---|---|---|---|---|---|---|---|---|
{TABLE}

Readings:

* The host router improves slowly with budget — {p16['err_all']*100:.1f}% error
  at N=16 → {p32['err_all']*100:.1f}% at N=32 — and its rerun reproducibility
  is poor everywhere (J {p16['jaccard_rerun']:.3f} at 16, validated on real
  draws in §7). Band-edge prompts churn under every fixed budget.
* Certified-sequential dominates every same-budget competitor on error,
  false-route, and regret. At δ=0.90 it spends {c90['mean_N']:.1f}
  rollouts/prompt (+{100*(cost_ratio_90-1):.0f}% over the host's N=16) and cuts
  its error by {red_c90_vs_p16*100:.0f}% relative ({(p16['err_all']-c90['err_all'])*100:.1f} points
  absolute); against double-budget plug-in N=32 it is still better
  ({c99['err_all']*100:.1f}% vs {p32['err_all']*100:.1f}%) at equal cost.
* Posterior-mean routing with the same EB prior tracks plug-in almost exactly
  (Δ = {pm_vs_plugin_16*100:.1f} points at N=16): replacing the point estimate
  by a posterior mean adds essentially nothing. **The whole certified gain
  comes from spending samples where the decision is uncertain, not from a
  better estimator** — which is precisely the claim that separates this from
  CurES/KGPS-style estimation improvements.
* KGPS-style PEU proxy at matched budgets lands far behind certification
  ({k18['err_all']*100:.1f}%–{k31['err_all']*100:.1f}% vs {c95['err_all']*100:.1f}%):
  utility-variance-driven allocation concentrates samples mid-band where the
  action is already certain, the exact failure certification avoids.
* Abstention buys near-zero false routes ({a90['false_route']*100:.1f}% at
  δ=0.9) at the price of large misses ({a90['missed_route']*100:.1f}%); plain
  sequential acting dominates it on regret. Abstention is not free.

## 5. Reproducibility (the G2 problem) — and why the gate is miscalibrated

No arm reaches J ≥ 0.90 at any registered budget, including the fixed-N
baselines ({p16['jaccard_rerun']:.3f} at 16, {p32['jaccard_rerun']:.3f} at 32;
real-draw values in §7 agree). Band-edge churn is intrinsic: prompts with
p̃ near 0.25 or 0.75 flip under resampling for every estimator. Certified has
the best action agreement of all arms ({c99['agreement_rerun']:.3f} vs
{p32['agreement_rerun']:.3f} for plug-in N=32) while its Jaccard is dragged by
small-set boundary effects. **G2 as written measures the wrong thing**; a
gate that fixed-N=32 fails cannot separate methods. Proposed replacement for
user decision: require rerun action-agreement ≥ 0.93 jointly with reference
accuracy (certified δ=0.99: {c99['agreement_rerun']:.3f} /
{c99['acc_all']*100:.1f}% correct; plug-in N=32:
{p32['agreement_rerun']:.3f} / {p32['acc_all']*100:.1f}%). No verdict changes
until you approve an amendment.

## 6. Decomposition — estimator rule vs adaptive sampling

Posterior-mean routing reproduces plug-in almost exactly at every N
({pm16['err_all']*100:.1f}% vs {p16['err_all']*100:.1f}% at N=16; Δ =
{pm_vs_plugin_16*100:.1f} points): with this prior and rule family, a better
point estimate is worthless. Certification's entire margin over the host
therefore comes from its stopping rule buying samples only where actions are
uncertain — {c90['mean_N']:.1f} meanN buys {red_c90_vs_p16*100:.0f}% less error,
and the unambiguous-subset error falls from {p16['err_unamb']*100:.1f}% to
{c90['err_unamb']*100:.1f}%. This is the cleanest possible statement of the
method's thesis: the bottleneck was never estimation quality; it is
action-uncertainty-blind budgets.

## 7. Nonparametric validation (real draws, no binomial assumption)

Subsampling the actual stored rollouts of both passes without replacement:

| config | prompts | err real | err parametric | J real | J parametric |
|---|---|---|---|---|---|
{np_table}

Real-draw numbers track the beta-binomial simulation closely, so the
verifier contamination present in the data does not break the parametric
model at these budgets.

## 8. Failure cases (worst prompts under the host router, N=16)

| qid | p̃ | reference | routed REPLAY | mean regret |
|---|---|---|---|---|
{FAIL_ROWS}

All six are REPLAY-band prompts sitting just above the lower threshold:
prompts with p̃ ∈ (0.25, 0.45) enter the buffer only
{lo_entry_median*100:.0f}% of the time at N=16 (median over
{band_lo_missed} such prompts). Misses, not false entries, carry the host's
regret structure — the mirror image of what set-instability metrics report.

## 9. What this does NOT establish

* Any trained-model consequence (E3's null warns exactly against assuming
  routing differences propagate to outcomes).
* Anything beyond one model/population/checkpoint; the oracle itself is a
  finite-sample estimate (hence §3's uncertain subset).
* VOI stopping, dynamic recertification, or host-integrated behaviour (B2/B3).

## 10. Pending

* Oracle top-up of the {UNC['n_uncertain']} uncertain prompts (+256 real
  draws each, same checkpoint) — transfer of the checkpoint to the GPU pod
  was interrupted and is retrying; B2 authorization can proceed without it,
  final B2 numbers will use it.
* Your call on the G1-cost reading and the §5 metric amendment before B2.
"""

open("B1_REPORT.md", "w").write(report)
print("wrote B1_REPORT.md,", len(report), "chars")
