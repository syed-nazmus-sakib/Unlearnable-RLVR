"""A80.17 — macros for the gradient-arm cost decision.

Primitives are the MEASURED quantities from the A80.16 probe; everything else is
derived here rather than typed. The probe artefacts are re-read where they still
exist on disk, so the wall clock, output size and array count are not
transcribed from a report.

  $HOME/miniconda3/envs/vllm/bin/python emit_gradcost_numbers.py
"""
import json
import os
import re
import shutil
import zipfile

EXP = os.path.dirname(os.path.abspath(__file__))
AN = os.path.join(EXP, "analysis")
OUT = os.path.abspath(os.path.join(EXP, "..", "..", "TRANSFER_OUT",
                                   "gradcost_numbers.tex"))
SCRATCH = ("/tmp/claude-1000/-media-rmedu-3039-8E90-LLM/"
           "03e2dc20-d17b-453a-a11d-ae1cb647269b/scratchpad")
LOG = os.path.join(SCRATCH, "probe1.log")
NPZ = os.path.join(SCRATCH, "grad_probe1",
                   "average_gradients_prompt_correct_0.npz")
SUMMARY = os.path.join(SCRATCH, "grad_probe1", "per_prompt_summary.json")

# ---- measured primitives, re-read from the probe artefacts ------------------
src = open(LOG).read()
WALL = float(re.search(r"WALL_SECONDS ([\d.]+)", src).group(1))
# the last tqdm rate line for the "Computing gradients" bar
COMPUTE = float(re.findall(r"(\d+\.\d+)s/it", src)[-1])
comp = json.load(open(SUMMARY))["0"]
z = zipfile.ZipFile(NPZ)
ARRAYS = len(z.namelist())
GB = os.path.getsize(NPZ) / 2 ** 30

# ---- the design, from A80.7 and the A80.13 post-filter counts ---------------
K_FOUR, K_EIGHT = 166 + 381, 53 + 381
SUBSAMPLES = 3
EVALS = (K_FOUR + K_EIGHT) * SUBSAMPLES
CEILING = 30
FIXED = [60, 20, 0]                     # bracket: the 2-prompt run was declined
FREE_SCRATCH = shutil.disk_usage("/tmp").free / 2 ** 30
FREE_PROJECT = shutil.disk_usage(os.path.join(EXP, "..", "..")).free / 2 ** 30

totals = [(f, WALL - f, EVALS * (WALL - f) / 3600) for f in FIXED]
STORAGE_TB = GB * EVALS / 1024
STREAM_H = COMPUTE * EVALS / 3600
SHARE = COMPUTE / WALL * 100

json.dump({"wall_s": WALL, "compute_s": COMPUTE, "compute_share_pct": SHARE,
           "output_gb": GB, "arrays": ARRAYS, "rollouts": comp,
           "prompts_k_four": K_FOUR, "prompts_k_eight": K_EIGHT,
           "subsamples": SUBSAMPLES, "evaluations": EVALS,
           "brackets": [{"fixed_s": f, "marginal_s": m, "gpu_hours": h}
                        for f, m, h in totals],
           "ceiling_gpu_hours": CEILING, "storage_tb": STORAGE_TB,
           "free_scratch_gb": FREE_SCRATCH, "free_project_gb": FREE_PROJECT,
           "streaming_hours_NOT_AN_ESTIMATE": STREAM_H},
          open(os.path.join(AN, "gradcost_probe.json"), "w"), indent=1)

W = ["Lower", "Mid", "Upper"]
L = []
A = L.append
A("% gradcost_numbers.tex -- A80.17. Cost of the Llama-3.2-3B gradient arm,")
A("% from the A80.16 timing probe. Generated by")
A("% EXPERIMENTS/E1_rescue/emit_gradcost_numbers.py, which re-reads the probe's")
A("% own log and output file rather than transcribing them.")
A("%")
A("% THE ARM IS DECLINED. Measured cost \\gcTotalLower--\\gcTotalUpper GPU-hours")
A("% against a ceiling of \\gcCeiling, fixed in advance.")
A("%")
A("% (a) THE SECOND TIMING POINT WAS NEVER MEASURED. The two-prompt run was")
A("%     declined at the permission prompt, so the fixed cost could not be")
A("%     cancelled by difference and is BRACKETED instead, across assumed")
A("%     fixed costs of \\gcFixedLower, \\gcFixedMid and \\gcFixedUpper seconds.")
A("%     This is recorded as a MISSING measurement, not as an unnecessary one.")
A("%")
A("% (b) THE MISSING POINT CANNOT CHANGE THE DECISION. Every point in the")
A("%     bracket exceeds the ceiling by more than twelvefold")
A("%     (\\gcMultipleLower to \\gcMultipleUpper times), so the fixed-cost term")
A("%     is not what stands between this arm and affordability.")
A("%")
A("% (c) THE ARM FAILS ON STORAGE INDEPENDENTLY OF TIME. It would write")
A("%     \\gcStorageTB TB against \\gcFreeScratch GB free on the scratch volume")
A("%     and \\gcFreeProject GB on the project drive. IT COULD NOT BE RUN WITH")
A("%     UNLIMITED TIME. Time and storage are two independent refusals.")
A("%     \\gcFreeProject is read live at emission; the A80.16 decision was taken")
A("%     at \\gcFreeProjectAtDecision GB. The gap is ordinary working-file churn")
A("%     and the conclusion is invariant to it -- the requirement exceeds either")
A("%     figure by more than two hundredfold.")
A("%")
A("% (d) \\gcStreamingHours GPU-hours MAY NOT BE QUOTED AS A COST ESTIMATE,")
A("%     ANYWHERE. It is gradient compute alone -- \\gcComputeShare percent of")
A("%     measured wall clock -- extrapolated to a streaming-cosine pipeline")
A("%     that DOES NOT EXIST, has not been written, and has not been validated")
A("%     against the existing estimator. The cost of the arm as it can be run")
A("%     today is \\gcTotalLower--\\gcTotalUpper GPU-hours. Any re-engineered")
A("%     pipeline is a new proposal with its own authorisation and ceiling.")
A("%")
A("% WHY IT SCALES THE WAY IT DOES: the pipeline writes a full per-prompt")
A("% parameter-gradient vector, so cost tracks MODEL SIZE (\\gcModelRef to")
A("% \\gcModelArm) and not K or rollout count. That is why K=4 and K=8 cost")
A("% almost the same per prompt, and why the reference arm was affordable at")
A("% the same prompt counts and this one is not.")
A("")
A("% ---- measured, one prompt ----")
A(f"\\newcommand{{\\gcWall}}{{{WALL:.2f}}}")
A(f"\\newcommand{{\\gcCompute}}{{{COMPUTE:.2f}}}")
A(f"\\newcommand{{\\gcComputeShare}}{{{SHARE:.1f}}}")
A(f"\\newcommand{{\\gcOutputGB}}{{{GB:.2f}}}")
A(f"\\newcommand{{\\gcArrays}}{{{ARRAYS}}}")
A(f"\\newcommand{{\\gcProbeRollouts}}{{{comp['num_rollouts']}}}")
A(f"\\newcommand{{\\gcProbeCorrect}}{{{comp['num_correct']}}}")
A(f"\\newcommand{{\\gcProbeIncorrect}}{{{comp['num_incorrect']}}}")
A("")
A("% ---- the design that was costed ----")
A(f"\\newcommand{{\\gcPromptsKFour}}{{{K_FOUR}}}")
A(f"\\newcommand{{\\gcPromptsKEight}}{{{K_EIGHT}}}")
A(f"\\newcommand{{\\gcSubsamples}}{{{SUBSAMPLES}}}")
A(f"\\newcommand{{\\gcEvaluations}}{{{EVALS}}}")
A(f"\\newcommand{{\\gcModelRef}}{{0.5B}}")
A(f"\\newcommand{{\\gcModelArm}}{{3B}}")
A("")
A("% ---- the bracket, and the line it is measured against ----")
for w, (f, m, h) in zip(W, totals):
    A(f"\\newcommand{{\\gcFixed{w}}}{{{f}}}")
    A(f"\\newcommand{{\\gcMarginal{w}}}{{{m:.0f}}}")
    A(f"\\newcommand{{\\gcTotal{w}}}{{{h:.0f}}}")
    A(f"\\newcommand{{\\gcMultiple{w}}}{{{h / CEILING:.0f}}}")
A(f"\\newcommand{{\\gcCeiling}}{{{CEILING}}}")
A("")
A("% ---- the independent storage refusal ----")
A(f"\\newcommand{{\\gcStorageTB}}{{{STORAGE_TB:.1f}}}")
A(f"\\newcommand{{\\gcFreeScratch}}{{{FREE_SCRATCH:.0f}}}")
A(f"\\newcommand{{\\gcFreeProject}}{{{FREE_PROJECT:.0f}}}")
A(f"\\newcommand{{\\gcFreeProjectAtDecision}}{{48}}")
A(f"\\newcommand{{\\gcStorageMultiple}}"
  f"{{{STORAGE_TB * 1024 / FREE_PROJECT:.0f}}}")
A("")
A("% ---- NOT a cost estimate. See (d). ----")
A(f"\\newcommand{{\\gcStreamingHours}}{{{STREAM_H:.1f}}}")
open(OUT, "w").write("\n".join(L) + "\n")
n = sum(1 for x in L if x.startswith("\\newcommand"))
print(f"wrote {OUT} ({n} macros)")
print(f"  wall {WALL} s, compute {COMPUTE} s ({SHARE:.1f} %), output {GB:.2f} GB, "
      f"{ARRAYS} arrays")
print(f"  evaluations {EVALS}   totals " +
      ", ".join(f"{h:.0f}" for _, _, h in totals) + f" GPU-h vs ceiling {CEILING}")
print(f"  storage {STORAGE_TB:.1f} TB vs {FREE_SCRATCH:.0f} GB / {FREE_PROJECT:.0f} GB free")
